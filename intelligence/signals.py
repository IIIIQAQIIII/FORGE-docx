"""Mission 02-A — Content Classifier Signals.

所有 content intent 的判定信号集中维护在这里，不允许散落在 classifier.py。

Signal 权重设计原则：
- 强信号（3 分）：多字、业务明确的短语，如“活动目标”“重点任务”“培训心得”。
- 中信号（2~2.5 分）：明确但可被多类共享的短语，如“存在问题”“工作总结”。
- 弱信号（0.5~1.5 分）：单字/泛词，如“方案”“活动”“总结”。
  弱信号单独出现时不能把 confidence 推到 0.9+。
"""

from __future__ import annotations

from dataclasses import dataclass, field


