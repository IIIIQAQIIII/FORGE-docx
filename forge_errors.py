CHECKPOINT_SOURCE_CHANGED = "CHECKPOINT_SOURCE_CHANGED"
JOB_NOT_FOUND = "JOB_NOT_FOUND"
ASSEMBLY_PROFILE_NOT_FOUND = "ASSEMBLY_PROFILE_NOT_FOUND"
ITEM_PRESERVATION_FAILED = "ITEM_PRESERVATION_FAILED"

# Template registry
TEMPLATE_ID_CONFLICT = "TEMPLATE_ID_CONFLICT"
TEMPLATE_PROFILE_NOT_FOUND = "PROFILE_NOT_FOUND"
TEMPLATE_NOT_FOUND = "TEMPLATE_NOT_FOUND"
NO_TEMPLATE_PLACEHOLDERS = "NO_TEMPLATE_PLACEHOLDERS"
MACRO_REJECTED = "MACRO_REJECTED"
UNSAFE_EXTERNAL_RELATIONSHIPS = "UNSAFE_EXTERNAL_RELATIONSHIPS"
MALFORMED_DOCX = "MALFORMED_DOCX"
ALIAS_CONFLICT = "ALIAS_CONFLICT"


def error_result(code: str, message: str, details: Optional[Any] = None) -> dict:
    """Build a consistent v1.2 structured error payload."""
    error: dict[str, Any] = {"code": code, "message": message}
    if details is not None:
        error["details"] = details
    return {"status": "error", "error": error}
